import { spawn } from 'node:child_process';
import {
  existsSync,
  readFileSync,
  rmSync,
  renameSync,
} from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const routePath = resolve(projectRoot, 'app/api/music/metadata/route.ts');
const parkedRoutePath = `${routePath}.caizen-android-build-disabled`;
const rawgRoutePath = resolve(projectRoot, 'app/api/games/rawg/route.ts');
const rawgParkedRoutePath = `${rawgRoutePath}.caizen-android-build-disabled`;
const exerciseMediaRoutePath = resolve(projectRoot, 'app/api/health/exercise-media/route.ts');
const exerciseMediaParkedRoutePath = `${exerciseMediaRoutePath}.caizen-android-build-disabled`;
const serverRoutes = [
  { routePath, parkedRoutePath, label: 'music metadata' },
  { routePath: rawgRoutePath, parkedRoutePath: rawgParkedRoutePath, label: 'RAWG' },
  { routePath: exerciseMediaRoutePath, parkedRoutePath: exerciseMediaParkedRoutePath, label: 'exercise media' },
];
const nextDevTypesPath = resolve(projectRoot, '.next', 'dev', 'types');
const clientPath = resolve(projectRoot, 'lib/music-metadata.ts');
const rawgClientPath = resolve(projectRoot, 'lib/games/rawg.ts');
const exerciseMediaClientPath = resolve(projectRoot, 'lib/health/exercise-media-provider.ts');
const configPath = resolve(projectRoot, 'next.config.mjs');
const packagePath = resolve(projectRoot, 'package.json');
const exampleEnvironmentPath = resolve(projectRoot, '.env.example');
const require = createRequire(import.meta.url);
const nextCliPath = require.resolve('next/dist/bin/next');

let routeIsParked = false;
let child;
let receivedSignal;

function recoverInterruptedPreparation() {
  for (const route of serverRoutes) {
    if (!existsSync(route.parkedRoutePath)) continue;
    if (existsSync(route.routePath)) {
      throw new Error(`Both the ${route.label} route and its Android-build parking file exist. Resolve them manually before building.`);
    }
    renameSync(route.parkedRoutePath, route.routePath);
    console.warn(`Recovered the ${route.label} route from an interrupted Android build.`);
  }
}

function verifyPermanentBoundary() {
  for (const serverRoute of serverRoutes) {
    if (!existsSync(serverRoute.routePath)) {
      throw new Error(`The website ${serverRoute.label} route is missing.`);
    }
    if (existsSync(serverRoute.parkedRoutePath)) {
      throw new Error('A stale Android-build route parking file is present.');
    }
  }

  const route = serverRoutes.map(serverRoute => readFileSync(serverRoute.routePath, 'utf8')).join('\n');
  const client = `${readFileSync(clientPath, 'utf8')}\n${readFileSync(rawgClientPath, 'utf8')}\n${readFileSync(exerciseMediaClientPath, 'utf8')}`;
  const config = readFileSync(configPath, 'utf8');
  const packageJson = JSON.parse(readFileSync(packagePath, 'utf8'));
  const exampleEnvironment = readFileSync(exampleEnvironmentPath, 'utf8');

  if (!/dynamic\s*=\s*['"]force-dynamic['"]/.test(route)) {
    throw new Error('The website metadata route must remain explicitly dynamic.');
  }
  if (!/runtime\s*=\s*['"]nodejs['"]/.test(route)) {
    throw new Error('The website metadata route must remain server-only.');
  }
  if (
    /NEXT_PUBLIC_SPOTIFY|SPOTIFY_CLIENT_(?:ID|SECRET)|RAWG_API_KEY/.test(client) ||
    /NEXT_PUBLIC_SPOTIFY|NEXT_PUBLIC_RAWG_API_KEY/.test(exampleEnvironment)
  ) {
    throw new Error('Spotify credentials must not enter public client configuration.');
  }
  if (!config.includes("process.env.CAPACITOR_BUILD === '1'")) {
    throw new Error('Next.js static export must remain gated to Capacitor builds.');
  }
  if (!String(packageJson.scripts?.['build:android:web'] || '').includes('build-android-web.mjs')) {
    throw new Error('build:android:web must use the Android export wrapper.');
  }
}

function parkServerRoute() {
  for (const serverRoute of serverRoutes) {
    renameSync(serverRoute.routePath, serverRoute.parkedRoutePath);
  }
  routeIsParked = true;
  // Next 16 keeps dev route validators under .next/dev/types. They can retain
  // an import of the parked website-only route and break this export's type
  // check, even though the route is intentionally absent from the Android
  // bundle. Clear only this generated cache; the normal .next/types contract
  // remains available and is regenerated by the build.
  if (existsSync(nextDevTypesPath)) {
    rmSync(nextDevTypesPath, { recursive: true, force: true });
  }
  console.log('Excluded server-only metadata routes from the Android export input.');
}

function restoreServerRoute() {
  if (!routeIsParked && !serverRoutes.some(route => existsSync(route.parkedRoutePath))) return;
  for (const serverRoute of serverRoutes) {
    if (existsSync(serverRoute.routePath)) {
      throw new Error(`The ${serverRoute.label} route reappeared while its parking file still exists; refusing to overwrite either file.`);
    }
    if (!existsSync(serverRoute.parkedRoutePath)) {
      throw new Error(`The parked ${serverRoute.label} route could not be found for restoration.`);
    }
  }
  for (const serverRoute of serverRoutes) {
    renameSync(serverRoute.parkedRoutePath, serverRoute.routePath);
  }
  routeIsParked = false;
  console.log('Restored the server-only metadata routes.');
}

function runNextBuild() {
  return new Promise((resolveBuild, rejectBuild) => {
    child = spawn(process.execPath, [nextCliPath, 'build'], {
      cwd: projectRoot,
      env: {
        ...process.env,
        CAPACITOR_BUILD: '1',
        NEXT_PUBLIC_CAPACITOR_BUILD: '1',
      },
      stdio: 'inherit',
    });
    child.once('error', rejectBuild);
    child.once('exit', (code, signal) => resolveBuild({ code, signal }));
  });
}

async function main() {
  const verifyOnly = process.argv.includes('--verify-only');
  if (verifyOnly && process.argv.length > 3) {
    throw new Error('The Android export boundary check accepts no additional arguments.');
  }

  if (!verifyOnly) recoverInterruptedPreparation();
  verifyPermanentBoundary();

  if (verifyOnly) {
    console.log('Android export boundary is configured correctly.');
    return;
  }

  const forwardSignal = (signal) => {
    receivedSignal = signal;
    if (child && !child.killed) child.kill(signal);
  };
  const handleInterrupt = () => forwardSignal('SIGINT');
  const handleTermination = () => forwardSignal('SIGTERM');
  const emergencyRestore = () => {
    try {
      restoreServerRoute();
    } catch {
      // The ordinary error path reports restoration failures. This handler is
      // only a final synchronous attempt during process shutdown.
    }
  };

  process.once('SIGINT', handleInterrupt);
  process.once('SIGTERM', handleTermination);
  process.on('exit', emergencyRestore);

  parkServerRoute();
  let result;
  try {
    result = await runNextBuild();
  } finally {
    restoreServerRoute();
    process.removeListener('exit', emergencyRestore);
    process.removeListener('SIGINT', handleInterrupt);
    process.removeListener('SIGTERM', handleTermination);
  }

  if (result.signal || receivedSignal) {
    throw new Error(`Android web build stopped by ${result.signal || receivedSignal}.`);
  }
  if (result.code !== 0) process.exitCode = result.code ?? 1;
}

main().catch((error) => {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
